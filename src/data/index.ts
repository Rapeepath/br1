import type { Breed, Market } from '../lib/types'
import breedsJson from './breeds.json'
import enJson from './en.json'
import marketJson from './market.json'

/**
 * A freely licensed Wikimedia Commons photo or video of the breed (`breeds[i].gallery`).
 * `src`/`srcSmall` are 1600 px / 640 px JPGs under public/images/gallery (for a video: its poster);
 * `video.url` is the remote upload.wikimedia.org .webm. See research_notes/<topic>/SCHEMA.md.
 */
export interface GalleryItem {
  kind: 'image' | 'video'
  src: string
  srcSmall: string
  width: number
  height: number
  page: string
  author: string
  license: string
  alt: string
  /** CSS object-position for cropped thumbnails */
  focus?: string
  video?: { url: string; duration: number; width: number; height: number }
}

/** English version of a breed's user-facing fields. Nested objects are complete, so `{ ...breed, ...record }` works. */
export type BreedEnglish = Pick<
  Breed,
  | 'nameEn'
  | 'origin'
  | 'tagline'
  | 'summary'
  | 'history'
  | 'appearance'
  | 'temperament'
  | 'idealFor'
  | 'considerations'
  | 'welfareNote'
  | 'funFact'
  | 'coat'
  | 'care'
  | 'health'
  | 'price'
> & { gallery: GalleryItem[] }

// Generated by `npm run data` from the research notes; validated in data.test.ts.
export const breeds = breedsJson as unknown as Breed[]
export const market = marketJson as unknown as Market
/** English content for /en: `records[breedId]` overlays a breed, `market` replaces the Thai market data. */
export const en = enJson as unknown as { records: Record<string, BreedEnglish>; market: Market }

const byId = new Map(breeds.map((b) => [b.id, b]))

export const getBreed = (id: string | undefined): Breed | undefined => (id ? byId.get(id) : undefined)

export const breedIds = breeds.map((b) => b.id)
